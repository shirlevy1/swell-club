-- event_photos.uploaded_by מוגדרת references public.profiles(id) on delete
-- cascade (migration 0003). היום זה לא בעיה - אין שום קוד שמוחק שורת
-- profiles בפועל ("עזיבת קהילה" ו"הסרת חבר/ה" הן soft-delete בלבד, מסמנות
-- status, לא מוחקות). אבל אם תכונת "מחיקת חשבון" מלאה תיבנה בעתיד (ראו
-- LEGAL-1 במסמך "שאלות לעורך/ת דין"), ותמומש כ-DELETE גולמי על profiles -
-- ה-CASCADE הזה ימחק אוטומטית גם כל תמונה שהאדם העלה לאלבומי מפגשים
-- משותפים, לכולם, לא רק את השיוך שלו/ה אליה. זה סותר ישירות את העיקרון
-- שכל מנגנון ה-soft-delete הקיים באתר בנוי סביבו - "היסטוריה משותפת
-- נשארת גם אחרי שמישהו עוזב". נמצא בביקורת מקיפה טרום-השקה (P2).
--
-- כשהתכונה תיבנה: או (1) לעדכן את שורות event_photos של האדם לפרופיל
-- אנונימי placeholder לפני מחיקת הפרופיל האמיתי, או (2) לשנות את העמודה
-- ל-on delete set null (דורש לאפשר null) - כך מחיקת פרופיל מנתקת את
-- הזיהוי בלי למחוק את התמונה, ונאכף במסד עצמו. בשני המקרים צריך גם
-- להחליט מה מוצג במקום השם (למשל "חבר/ה שעזב/ה").
-- ============================================================================

