-- ============================================================================
-- Swell — שחזור הרשאות service_role על טבלאות ה-public
-- ============================================================================
-- גילינו (בדיבוג תזכורות Push) ש-service_role לא היה לו בכלל SELECT
-- על טבלאות כמו events — למרות שזה תפקיד-העל שאמור לעקוף RLS. עקיפת
-- RLS והרשאות ברמת הטבלה (GRANT) הן שתי שכבות נפרדות לגמרי ב-Postgres:
-- service_role עוקף RLS דרך תכונת bypassrls, אבל עדיין צריך GRANT רגיל
-- על כל טבלה, בדיוק כמו כל תפקיד אחר. ברוב פרויקטי Supabase זה כבר
-- מוגדר כברירת מחדל — כאן זה היה חסר, וזה שבר בשקט את כל נתיב
-- ההתראות המיידיות (api/push/notify-*) ואת ה-cron (api/push/send),
-- כי שניהם משתמשים ב-service_role כדי לקרוא בלי session מחובר.
--
-- אין כאן ויתור על אבטחה: service_role כבר עוקף RLS לגמרי בכל מקרה,
-- הוא מפתח-שרת בלבד שלעולם לא נחשף לדפדפן (SUPABASE_SERVICE_ROLE_KEY
-- בלי NEXT_PUBLIC_), ואין תרחיש שבו "יותר מדי הרשאות" לתפקיד הזה
-- משנה משהו בפועל.
-- ============================================================================

grant all privileges on all tables in schema public to service_role;

-- כדי שזה לא יקרה שוב בשקט לכל טבלה חדשה שניצור בעתיד
alter default privileges in schema public grant all on tables to service_role;
