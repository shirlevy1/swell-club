-- Swell — הצטרפות עצמית לקהילה תמיד יוצרת בקשה ממתינה, לא חברות מאושרת
-- ============================================================================
-- club_members_join_self (0001_init.sql) בדקה רק profile_id=עצמי ו-
-- role='member' - בלי לבדוק status בכלל. העמודה הזו ברירת המחדל שלה
-- היא 'approved' (0002_membership_approval.sql), כלומר הכנסה עצמית,
-- אם הייתה מתבצעת, הייתה הופכת מישהו לחבר/ה מאושר/ת מיידית, בלי
-- לעבור את תהליך האישור של המנהלת בכלל.
--
-- לא מנוצל היום בפועל: יש קהילה אחת בלבד, לכל משתמש/ת כבר יש בדיוק
-- שורת חברות אחת (נוצרת אוטומטית ע"י handle_new_user() בהרשמה), והמפתח
-- הראשי של הטבלה (club_id, profile_id) מונע שורה כפולה לאותה קהילה -
-- אין היום "דלת שנייה" להיכנס דרכה. אבל ברגע שתהיה קהילה נוספת
-- באפליקציה, הפער הזה נפתח מיידית - מי שלא חבר/ה בקהילה ב' יכול/ה
-- להצטרף אליה כמאושר/ת, בלי לעבור אף אישור. נמצא ותועד בביקורת
-- מוכנות ההשקה (SEC-1).
-- ============================================================================

drop policy if exists "club_members_join_self" on public.club_members;

create policy "club_members_join_self" on public.club_members
for insert to authenticated with check (
  profile_id = auth.uid() and role = 'member' and status = 'pending'
);
