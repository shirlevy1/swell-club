-- הסרנו את אפשרות "אחר" מטופס המגדר (הרשמה ועריכת פרופיל) — מעכשיו
-- אפשר לבחור רק "אישה"/"גבר". זה פותר קדימה את אי-ההתאמה באחוזי
-- נשים/גברים בדוחות (שלא הגיעו ל-100% כשמישהו/י היה/הייתה "אחר").
--
-- זה לא נוגע במי שכבר בקהילה: מי שכבר בחר/ה "אחר", או שמעולם לא מילא/ה
-- מגדר (למשל הצטרפות מלפני שהשדה הזה נוסף לאתר), מסווג/ת עכשיו כ"אישה" —
-- לפי בקשה מפורשת של שיר, לא ניחוש. אחרת אותם אנשים היו נשארים בלי
-- סיווג לצמיתות, ושוברים את אחוזי הדוחות עד שהם עצמם היו נכנסים
-- לערוך את הפרופיל שלהם.
--
-- לא מוחקים את הערך 'other' מה-enum עצמו במסד — Postgres לא תומך בהסרת
-- ערך מ-enum בלי לבנות טיפוס חדש ולהחליף את העמודה, וזה לא נדרש כאן:
-- אחרי העדכון הזה שום שורה לא תשתמש בו יותר, והטופס כבר לא מציע אותו.
update public.profiles
set gender = 'female'
where gender is null or gender = 'other';
