-- Swell — אינדקס על club_members(profile_id)
-- ============================================================================
-- המפתח הראשי של הטבלה הוא (club_id, profile_id) — מורכב, עם club_id
-- קודם. getViewer() (רץ בכל עמוד מוגן, לכל מבקר/ת) שואל רק
-- .eq("profile_id", userId), בלי club_id — כי זה בדיוק מה שהשאילתה הזו
-- מנסה לגלות. שאילתה כזו לא יכולה להשתמש ביעילות במפתח הראשי, כי
-- profile_id הוא העמודה השנייה שלו, לא הראשונה — בלי אינדקס נפרד,
-- Postgres סורק את כל הטבלה כדי למצוא שורה אחת.
--
-- לא מורגש כרגע (קהילת בדיקה משפחתית, כמה שורות בודדות), אבל זו
-- בדיוק השאילתה הכי נפוצה באתר — כל עמוד, כל משתמש/ת — ותאט בהדרגה
-- ככל שהקהילה האמיתית תגדל. תוספת בלבד: שום שינוי בהתנהגות, שום
-- מחיקה, רק אינדקס נוסף לצד הקיים.
-- ============================================================================

create index club_members_profile_idx on public.club_members (profile_id);
