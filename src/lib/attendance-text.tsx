/**
 * "{subject} ב-Y מתוך X מפגשים החודש" — X ו-Y תמיד ספרות, גם כש-Y הוא
 * 0 או 1: זו כאן יחס/סטטיסטיקה ולא ספירה של שם עצם, ולכן לא דורשת את
 * "מפגש אחד" הכתוב במלא כמו במקומות אחרים באפליקציה.
 *
 * subject מגיע כפרמטר כדי שהניסוח יתאים גם לגוף שני רבים ("הייתם
 * איתנו", בעמוד הפרופיל של עצמך — ברבים כמו בכל שאר הממשק) וגם לגוף
 * שלישי עם הטיה מגדרית ("היה/הייתה איתנו", בעמוד הניהול של חבר אחר) —
 * בלי לשכפל את כל המשפט פעמיים.
 *
 * "החודש" הוא חלון נגלל של 30 יום אחורה מעכשיו (למשל 17.7–16.8 כולל),
 * לא חודש קלנדרי — ראו getRecentMonthStats ב-lib/data.ts.
 *
 * קובץ פשוט בלי "use client" בכוונה: משמש גם את profile/page.tsx וגם
 * את admin/members/[id]/page.tsx, שתי רכיבי שרת — פונקציה שמייצרת JSX
 * וצריכה לרוץ משני המקומות האלה לא יכולה לשבת בקובץ "use client".
 */
export function monthAttendanceLine(
  subject: string,
  attended: number,
  total: number,
) {
  if (total === 0) return "לא היו מפגשים החודש";
  return (
    <>
      {subject} ב־<span className="ltr-nums">{attended}</span> מתוך{" "}
      {total === 1 ? (
        "מפגש אחד"
      ) : (
        <>
          <span className="ltr-nums">{total}</span> מפגשים
        </>
      )}{" "}
      החודש
    </>
  );
}
